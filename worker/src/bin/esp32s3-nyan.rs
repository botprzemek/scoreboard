#![no_std]
#![no_main]

use core::panic::PanicInfo;

use esp_hal::time::Instant;
use hub75::{Color, DisplayBuffer, LedOutputs, LedPeripherals};
use static_cell::StaticCell;

esp_bootloader_esp_idf::esp_app_desc!();

const WIDTH: usize = 64;
const HEIGHT: usize = 32;
const HALF_HEIGHT: usize = HEIGHT / 2;
const DISPLAY_BRIGHTNESS: u8 = 30;
const FRAME_DURATION_MICROS: u64 = 70_000;

const NAVY: Color = [0, 51, 102];
const OUTLINE: Color = [0, 0, 0];
const ICING_PINK: Color = [255, 153, 255];
const CAT_GRAY: Color = [153, 153, 153];
const RAINBOW_RED: Color = [255, 0, 0];
const RAINBOW_ORANGE: Color = [255, 153, 0];
const RAINBOW_VIOLET: Color = [102, 51, 255];
const RAINBOW_YELLOW: Color = [255, 255, 0];
const POP_TART_TAN: Color = [255, 204, 153];
const RAINBOW_BLUE: Color = [0, 153, 255];
const RAINBOW_GREEN: Color = [51, 255, 0];
const STAR_WHITE: Color = [255, 255, 255];
const SPRINKLE_PINK: Color = [255, 51, 153];
const CHEEK_PINK: Color = [255, 153, 153];

static DISPLAY: StaticCell<DisplayBuffer<WIDTH, HEIGHT, HALF_HEIGHT>> = StaticCell::new();

#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    loop {}
}

#[inline(always)]
const fn pixel_color(code: u8) -> Color {
    match code {
        b'#' => OUTLINE,
        b'P' => ICING_PINK,
        b'G' => CAT_GRAY,
        b'R' => RAINBOW_RED,
        b'O' => RAINBOW_ORANGE,
        b'V' => RAINBOW_VIOLET,
        b'Y' => RAINBOW_YELLOW,
        b'T' => POP_TART_TAN,
        b'B' => RAINBOW_BLUE,
        b'E' => RAINBOW_GREEN,
        b'W' => STAR_WHITE,
        b'S' => SPRINKLE_PINK,
        b'C' => CHEEK_PINK,
        _ => NAVY,
    }
}

fn draw_frame(
    display: &mut DisplayBuffer<WIDTH, HEIGHT, HALF_HEIGHT>,
    frame: &[&[u8; WIDTH]; HEIGHT],
) {
    for (y, row) in frame.iter().enumerate() {
        for (x, &code) in row.iter().enumerate() {
            display.set_pixel(x, y, pixel_color(code));
        }
    }
    display.prepare_bitplanes();
}

#[esp_hal::main]
fn main() -> ! {
    let peripherals = esp_hal::init(esp_hal::Config::default());

    let led_peripherals = LedPeripherals::new(
        peripherals.GPIO42,
        peripherals.GPIO41,
        peripherals.GPIO40,
        peripherals.GPIO38,
        peripherals.GPIO39,
        peripherals.GPIO37,
        peripherals.GPIO45,
        peripherals.GPIO36,
        peripherals.GPIO48,
        peripherals.GPIO35,
        peripherals.GPIO21,
        peripherals.GPIO2,
        peripherals.GPIO47,
        peripherals.GPIO14,
    );

    let mut outputs = LedOutputs::from_peripherals(led_peripherals);
    let display = DISPLAY.init_with(DisplayBuffer::new);
    display.set_brightness(100);

    let mut frame_index = 0usize;
    draw_frame(display, &NYAN_FRAMES[frame_index]);
    let mut last_frame_at = Instant::now();

    loop {
        if last_frame_at.elapsed().as_micros() >= FRAME_DURATION_MICROS {
            last_frame_at = Instant::now();
            frame_index = (frame_index + 1) % NYAN_FRAMES.len();
            draw_frame(display, &NYAN_FRAMES[frame_index]);
        }

        outputs.render_bcm_frame_sync_with_brightness(display.bitplanes(), DISPLAY_BRIGHTNESS);
    }
}

